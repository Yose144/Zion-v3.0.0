import { chromium } from 'playwright';
const browser = await chromium.launch({ channel: 'chrome' });
const ctx = await browser.newContext({ viewport: { width: 1440, height: 900 }, extraHTTPHeaders: { 'x-render-audit': '1' } });
const page = await ctx.newPage();
const errs = [];
page.on('console', (m) => { if (m.type() === 'error') errs.push(m.text()); });
page.on('pageerror', (e) => errs.push(String(e)));
await page.goto('http://127.0.0.1:3126/present/kralovstvi-srdce', { waitUntil: 'networkidle', timeout: 120000 });
await page.waitForTimeout(9000);
await page.screenshot({ path: '/tmp/ark-present2.png' });
console.log('errors:', errs.length, JSON.stringify(errs.slice(0, 4)));
await browser.close();
