export const LANG_OVERRIDES: Record<'es' | 'pt' | 'fr', LangOverrides> = { es, pt, fr };

/** Překlad z override souboru; `undefined` = nemáme, volej fallback. */
export function overrideFor(lang: string, section: string, key: string): string | undefined {
  if (lang !== 'es' && lang !== 'pt' && lang !== 'fr') return undefined;
  return LANG_OVERRIDES[lang][section]?.[key];
}
