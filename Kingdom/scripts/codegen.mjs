#!/usr/bin/env node
/**
 * Registry codegen — skenuje apps/kingdom/src/portals a vygeneruje registry.
 *
 * Konvence portálu (vynucená check-boundaries.mjs):
 *   src/portals/<cesta>/manifest.ts   → export const manifest
 *   src/portals/<cesta>/Portal.tsx    → export default (server komponenta)
 *
 * Cokoliv, co tenhle soubor vygeneruje, se needituje ručně.
 */
import { existsSync, readdirSync, statSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const appDir = join(here, '..', 'apps', 'kingdom');
const portalsDir = join(appDir, 'src', 'portals');
const outFile = join(appDir, 'src', 'core', 'registry', 'index.ts');

function findPortalDirs(dir, acc = []) {
  if (!existsSync(dir)) return acc;
  if (existsSync(join(dir, 'manifest.ts'))) {
    acc.push(dir);
    return acc;
  }
  for (const entry of readdirSync(dir)) {
    if (entry.startsWith('.') || entry === 'node_modules') continue;
    const full = join(dir, entry);
    if (statSync(full).isDirectory()) findPortalDirs(full, acc);
  }
  return acc;
}

const dirs = findPortalDirs(portalsDir).sort();
const portals = [];
const skipped = [];

for (const dir of dirs) {
  if (!existsSync(join(dir, 'Portal.tsx'))) {
    skipped.push(`${relative(portalsDir, dir)} (chybí Portal.tsx)`);
    continue;
  }
  const rel = relative(portalsDir, dir).split(sep).join('/');
  portals.push({ dir, rel });
}

const imports = portals
  .map(
    ({ rel }, i) =>
      `import { manifest as m${i} } from '../../portals/${rel}/manifest';\n` +
      `import v${i} from '../../portals/${rel}/Portal';`,
  )
  .join('\n');

const entries = portals
  .map(({ rel }, i) => `  { manifest: m${i}, view: v${i} as unknown as PortalView }, // ${rel}`)
  .join('\n');

const content = `// AUTO-GENERATED by scripts/codegen.mjs — neupravuj ručně.
// Spusť \`npm run codegen\` po přidání nebo odebrání portálu.
${imports ? `\n${imports}\n` : ''}
import type { ComponentType } from 'react';
import type { Locale, PortalManifest } from '@zion/contract';

export type PortalView = ComponentType<{ locale: Locale }>;

export interface PortalEntry {
  manifest: PortalManifest;
  view: PortalView;
}

const entries: PortalEntry[] = [
${entries || '  // žádné portály'}
];

/** Všechny portály v deterministickém pořadí: manifest.order, pak manifest.id. */
export const portals: PortalManifest[] = entries
  .map((entry) => entry.manifest)
  .sort((a, b) => (a.order ?? 999) - (b.order ?? 999) || a.id.localeCompare(b.id));

const registry = new Map(entries.map((entry) => [entry.manifest.id, entry]));

export function portalById(id: string): PortalEntry | undefined {
  return registry.get(id);
}

export function otherPortals(id: string): PortalManifest[] {
  return portals.filter((portal) => portal.id !== id);
}
`;

mkdirSync(dirname(outFile), { recursive: true });
writeFileSync(outFile, content, 'utf8');

console.log(`codegen: ${portals.length} portálů → ${relative(process.cwd(), outFile)}`);
for (const rel of portals.map((p) => p.rel)) console.log(`  · ${rel}`);
for (const s of skipped) console.warn(`  ! přeskočeno: ${s}`);
